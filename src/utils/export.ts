import type { Process, SimulationResult } from '../engine/types';
import { parseProcessCSV } from '../engine/validation';

/** Export processes to CSV string */
export function exportProcessesToCSV(processes: Process[]): string {
  const header = 'pid,name,arrivalTime,burstTime,priority';
  const rows = processes.map(
    p => `${p.pid},${p.name},${p.arrivalTime},${p.burstTime},${p.priority}`
  );
  return [header, ...rows].join('\n');
}

/** Export simulation results to CSV string */
export function exportResultsToCSV(result: SimulationResult): string {
  const header = 'pid,name,arrivalTime,burstTime,priority,completionTime,turnaroundTime,waitingTime,responseTime';
  const rows = result.processes.map(p =>
    `${p.pid},${p.name},${p.arrivalTime},${p.burstTime},${p.priority},${p.completionTime ?? ''},${p.turnaroundTime ?? ''},${p.waitingTime ?? ''},${p.responseTime ?? ''}`
  );
  const metricsSection = [
    '',
    '# Aggregate Metrics',
    `algorithm,${result.algorithm}`,
    `averageWaitingTime,${result.metrics.averageWaitingTime}`,
    `averageTurnaroundTime,${result.metrics.averageTurnaroundTime}`,
    `averageResponseTime,${result.metrics.averageResponseTime}`,
    `cpuUtilization,${result.metrics.cpuUtilization}%`,
    `throughput,${result.metrics.throughput} processes/unit`,
    `contextSwitches,${result.metrics.contextSwitches}`,
  ];
  return [header, ...rows, ...metricsSection].join('\n');
}

/** Export scheduling summary to text */
export function exportSummaryText(result: SimulationResult): string {
  const lines: string[] = [
    '╔══════════════════════════════════════════╗',
    '║       SCHEDULIX — Simulation Summary     ║',
    '╚══════════════════════════════════════════╝',
    '',
    `Algorithm: ${result.algorithm}`,
    result.algorithmConfig.timeQuantum
      ? `Time Quantum: ${result.algorithmConfig.timeQuantum}`
      : '',
    `Total Simulation Time: ${result.totalTime} units`,
    '',
    '── Performance Metrics ────────────────────',
    `Avg Waiting Time:     ${result.metrics.averageWaitingTime} units`,
    `Avg Turnaround Time:  ${result.metrics.averageTurnaroundTime} units`,
    `Avg Response Time:    ${result.metrics.averageResponseTime} units`,
    `CPU Utilization:      ${result.metrics.cpuUtilization}%`,
    `Throughput:           ${result.metrics.throughput} proc/unit`,
    `Context Switches:     ${result.metrics.contextSwitches}`,
    '',
    '── Process Details ────────────────────────',
    'PID | Name | AT | BT | CT  | TAT | WT  | RT',
    '─'.repeat(50),
    ...result.processes.map(p =>
      `P${String(p.pid).padEnd(3)} | ${p.name.padEnd(4)} | ${String(p.arrivalTime).padEnd(2)} | ${String(p.burstTime).padEnd(2)} | ${String(p.completionTime ?? '-').padEnd(3)} | ${String(p.turnaroundTime ?? '-').padEnd(3)} | ${String(p.waitingTime ?? '-').padEnd(3)} | ${p.responseTime ?? '-'}`
    ),
    '',
    '── Gantt Chart ─────────────────────────────',
    result.ganttChart.map(seg =>
      `[${seg.processName}] ${seg.startTime}→${seg.endTime} (${seg.duration}u)`
    ).join('  '),
    '',
    `Generated by Schedulix at ${new Date().toISOString()}`,
  ].filter(l => l !== null);

  return lines.join('\n');
}

/** Trigger browser file download */
export function downloadFile(content: string, filename: string, mimeType = 'text/csv'): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

